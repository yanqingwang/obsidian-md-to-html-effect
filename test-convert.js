// Comprehensive validation on FULL html
function validate(html) {
    const issues = [];

    // Frontmatter stripped
    if (html.includes('title: 小狗测试')) issues.push('Frontmatter not stripped');

    // Table structure
    if (html.includes('<table>')) {
        if (!html.includes('<thead>')) issues.push('Table missing <thead>');
        if (!html.includes('<tbody>')) issues.push('Table missing <tbody>');
        // Check no th inside tbody
        const tbodyStart = html.indexOf('<tbody>');
        const tbodyContent = html.slice(tbodyStart, html.indexOf('</tbody>'));
        if (tbodyContent.includes('<th>')) issues.push('<th> found inside <tbody>');
    }

    // Strikethrough
    if (html.includes('删除线测试') && !html.includes('<del>')) issues.push('Strikethrough not converted');
    if (html.includes('这行文字应该被删除线') && !html.includes('<del>')) issues.push('Strikethrough inline not converted');

    // Heading count
    const h1Count = (html.match(/<h1>/g) || []).length;
    if (h1Count !== 1) issues.push(`Expected exactly 1 <h1>, found ${h1Count}`);
    const h2Count = (html.match(/<h2>/g) || []).length;
    if (h2Count < 2) issues.push(`Expected at least 2 <h2>, found ${h2Count}`);
    const h3Count = (html.match(/<h3>/g) || []).length;
    if (h3Count < 8) issues.push(`Expected at least 8 <h3>, found ${h3Count}`);
    const h4Count = (html.match(/<h4>/g) || []).length;
    if (h4Count < 1) issues.push('Missing <h4>');

    // Code blocks
    if (!html.includes('<pre><code class="language-python"')) issues.push('Code block missing language class');

    // Inline code
    if (!html.includes('<code>npm run build</code>')) issues.push('Inline code not converted');

    // Lists
    if (!html.includes('<ul>')) issues.push('Unordered list missing');
    if (!html.includes('<ol>')) issues.push('Ordered list missing');

    // Blockquotes
    if (!html.includes('<blockquote>')) issues.push('Blockquote missing');
    if (!html.includes('这是一段引用文字')) issues.push('Blockquote content missing');

    // Links
    if (!html.includes('href="https://openai.com"')) issues.push('External link broken');
    if (!html.includes('<a href="另一个笔记">')) issues.push('Wiki-link [[page]] not converted');
    if (!html.includes('<a href="测试页面">显示名称</a>')) issues.push('Wiki-link [[page|alias]] not converted');

    // Images
    if (!html.includes('<img alt="小狗" src="https://example.com/dog.png"')) issues.push('Image not converted');

    // Horizontal rule
    if (!html.includes('<hr>')) issues.push('HR missing');

    // HTML entity escaping
    if (html.includes('&lt;p&gt;这段文字应该被转义&lt;/p&gt;')) {
        // correct
    } else if (html.includes('<p>这段文字')) {
        issues.push('HTML entities not escaped - raw tags rendered');
    }

    // Theme toggle in full HTML
    if (!html.includes('theme-toggle')) issues.push('Theme toggle button missing');
    if (!html.includes('body.light')) issues.push('Light theme CSS missing');

    // Print CSS
    if (!html.includes('@media print')) issues.push('Print CSS missing');
    if (!html.includes('.theme-toggle { display:none; }') && !html.includes('.theme-toggle { display: none; }')) {
        // Check in minified form
        if (!html.includes('display:none')) issues.push('Print hide toggle missing');
    }

    // DOCTYPE and HTML structure
    if (!html.startsWith('<!DOCTYPE html>')) issues.push('Missing DOCTYPE');
    if (!html.includes('<html lang="zh-CN">')) issues.push('Missing html lang');
    if (!html.includes('<meta charset="UTF-8">')) issues.push('Missing charset meta');
    if (!html.includes('<meta name="viewport"')) issues.push('Missing viewport meta');
    if (!html.includes('</html>')) issues.push('Missing closing html tag');

    // Inline CSS
    if (!html.includes('<style>')) issues.push('Missing <style> tag');

    // Bold, italic, bold+italic
    if (!html.includes('<strong>加粗文字</strong>')) issues.push('Bold text not converted');
    if (!html.includes('<em>斜体文字</em>')) issues.push('Italic text not converted');
    if (!html.includes('<em><strong>加粗斜体</strong></em>')) issues.push('Bold+italic not converted correctly');

    // Subtitle generation
    if (!html.includes('Generated by MD to HTML Effectiveness')) issues.push('Missing subtitle/footer');

    return issues;
}

